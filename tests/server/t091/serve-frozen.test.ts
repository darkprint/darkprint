/* ============================================================
   T091 — AC2 and AC3, through `serveFile`

   The half of this task that a caller can see: `serveFile`
   prefers the frozen artefact, and still serves a release that
   predates the freeze.

   ── why this file exists at all, given t090/serve.test.ts ──
   `tests/server/t090/serve.test.ts`'s AC6 cell has measured this
   property since T050 and has been red the whole time, and its
   own comments record why it CANNOT go further: "the fixture does
   not persist anything before re-scoring: it *cannot*, because
   the write verb belongs to another task". §T091's AC3 forbids
   weakening that cell and this suite does not touch it.

   What this partition can do that it cannot is the point: T091
   may call `persistArtefacts`, so the frozen half of the property
   gets a witness here — with its own control — instead of resting
   on one criterion in another task's file that nobody could make
   green from inside.

   ── every release here has a run-unique digest ──
   See `uniqueDot` in fixtures.ts. `S3_BUCKET` is one bucket for
   the whole machine and `keyForDigest` puts no run in the key, so
   a suite that seeded a shipped bundle unperturbed would freeze
   its fixture over somebody else's real artefact and delete the
   key at teardown.
   ============================================================ */

